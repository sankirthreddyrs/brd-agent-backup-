import io
from datetime import datetime, timezone
from typing import Optional
from app.schemas import RunResult, Requirement


def _format_source(req: Requirement) -> str:
    """Format verified citations for a requirement."""
    sources = []
    for ev in req.evidence:
        if ev.verified:
            loc = ""
            if ev.page is not None:
                loc = f", page {ev.page}"
            elif ev.line is not None:
                loc = f", line {ev.line}"
            elif ev.box_2d is not None:
                loc = f", region {ev.box_2d}"
            sources.append(f"{ev.file_name} ({ev.kind}{loc})")

    return "; ".join(sources) if sources else "None"


def build_brd_markdown(
    project_name: str,
    result: RunResult,
    approved_only: bool = False,
) -> str:
    """
    Build Markdown BRD following section 13 of the PRD:
    - ## 1. Source artifacts
    - ## 2. Functional requirements
    - ## 3. Non-functional requirements
    - ## 4. Constraints
    - ## 5. Unverified items (not confirmed)
    - ## 6. Conflicts ([Resolved] / [Unresolved])
    - ## 7. Open questions (with Answer: {answer} when answered)
    Strict Rule: Sections 2-4 contain ONLY verified requirements with review_status != 'rejected'.
    If approved_only=True, only review_status == 'approved' are included.
    Unverified requirements are strictly placed in Section 5.
    """
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    # Filter confirmed vs unverified
    confirmed_reqs = []
    unverified_reqs = []

    for req in result.requirements:
        if req.verification_status != "verified":
            unverified_reqs.append(req)
        elif req.review_status == "rejected":
            continue
        elif approved_only and req.review_status != "approved":
            continue
        else:
            confirmed_reqs.append(req)

    func_reqs = [r for r in confirmed_reqs if r.type == "functional"]
    nfunc_reqs = [r for r in confirmed_reqs if r.type == "non-functional"]
    const_reqs = [r for r in confirmed_reqs if r.type == "constraint"]

    lines = [
        f"# Business Requirements Document: {project_name}",
        f"Generated by BRD Agent | {now_str} | Run {result.run_id} | Mode: {result.mode}",
        "",
        "## 1. Source artifacts",
    ]

    if result.artifacts:
        for art in result.artifacts:
            kb = art.size_bytes / 1024
            lines.append(f"- **{art.file_name}** ({art.kind}, {kb:.1f} KB)")
    else:
        lines.append("_No source artifacts recorded._")

    lines.append("")
    lines.append("## 2. Functional requirements")
    if func_reqs:
        for r in func_reqs:
            src = _format_source(r)
            lines.append(f"- **{r.id}**: {r.text}")
            lines.append(f"  - _Source_: {src}")
    else:
        lines.append("_No verified functional requirements._")

    lines.append("")
    lines.append("## 3. Non-functional requirements")
    if nfunc_reqs:
        for r in nfunc_reqs:
            src = _format_source(r)
            lines.append(f"- **{r.id}**: {r.text}")
            lines.append(f"  - _Source_: {src}")
    else:
        lines.append("_No verified non-functional requirements._")

    lines.append("")
    lines.append("## 4. Constraints")
    if const_reqs:
        for r in const_reqs:
            src = _format_source(r)
            lines.append(f"- **{r.id}**: {r.text}")
            lines.append(f"  - _Source_: {src}")
    else:
        lines.append("_No verified constraints._")

    lines.append("")
    lines.append("## 5. Unverified items (not confirmed)")
    if unverified_reqs:
        for r in unverified_reqs:
            lines.append(f"- **{r.id}**: {r.text} *(Reason: unverified source evidence)*")
            for ev in r.evidence:
                lines.append(f"  - Evidence claimed: {ev.file_name} ({ev.kind}) - {ev.verify_note}")
    else:
        lines.append("_None. All extracted requirements passed evidence verification._")

    lines.append("")
    lines.append("## 6. Conflicts")
    if result.conflicts:
        for c in result.conflicts:
            status = "Resolved" if c.resolved else "Unresolved"
            lines.append(f"- **[{status}] [{c.severity.upper()}] ({', '.join(c.requirement_ids)})**: {c.description}")
    else:
        lines.append("_No conflicts detected._")

    lines.append("")
    lines.append("## 7. Open questions")
    if result.gaps:
        for g in result.gaps:
            ans = f" - *Answer: {g.answer}*" if g.answer else ""
            lines.append(f"- **{g.category.title()}**: {g.question}{ans}")
    else:
        lines.append("_No open requirement gaps detected._")

    return "\n".join(lines)


def build_brd_docx(
    project_name: str,
    result: RunResult,
    approved_only: bool = False,
) -> Optional[bytes]:
    """
    Build Word DOCX document with python-docx if installed.
    Matches the exact 7 sections and strict verification filtering rules of build_brd_markdown.
    Returns bytes or None if python-docx is unavailable.
    """
    try:
        import docx  # type: ignore # pyrefly: ignore
        from docx.shared import Inches, Pt, RGBColor  # type: ignore # pyrefly: ignore
    except ImportError:
        return None

    doc = docx.Document()

    # Title & Metadata
    title_p = doc.add_heading(f"Business Requirements Document: {project_name}", level=0)
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    meta_p = doc.add_paragraph(f"Generated by BRD Agent | {now_str} | Run {result.run_id} | Mode: {result.mode}")
    meta_p.runs[0].font.italic = True
    meta_p.runs[0].font.size = Pt(10)

    # Filter confirmed vs unverified
    confirmed_reqs = []
    unverified_reqs = []

    for req in result.requirements:
        if req.verification_status != "verified":
            unverified_reqs.append(req)
        elif req.review_status == "rejected":
            continue
        elif approved_only and req.review_status != "approved":
            continue
        else:
            confirmed_reqs.append(req)

    func_reqs = [r for r in confirmed_reqs if r.type == "functional"]
    nfunc_reqs = [r for r in confirmed_reqs if r.type == "non-functional"]
    const_reqs = [r for r in confirmed_reqs if r.type == "constraint"]

    # 1. Source artifacts
    doc.add_heading("1. Source artifacts", level=1)
    if result.artifacts:
        for art in result.artifacts:
            kb = art.size_bytes / 1024
            p = doc.add_paragraph(style="List Bullet")
            r1 = p.add_run(f"{art.file_name} ")
            r1.bold = True
            p.add_run(f"({art.kind}, {kb:.1f} KB)")
    else:
        doc.add_paragraph("No source artifacts recorded.")

    # Helper for requirement sections
    def add_req_list(reqs: list[Requirement], empty_msg: str):
        if reqs:
            for r in reqs:
                p = doc.add_paragraph(style="List Bullet")
                r_id = p.add_run(f"{r.id}: ")
                r_id.bold = True
                p.add_run(r.text)

                src = _format_source(r)
                p_src = doc.add_paragraph(style="Normal")
                p_src.paragraph_format.left_indent = Inches(0.5)
                r_src = p_src.add_run(f"Source: {src}")
                r_src.italic = True
                r_src.font.size = Pt(9.5)
        else:
            doc.add_paragraph(empty_msg)

    # 2. Functional requirements
    doc.add_heading("2. Functional requirements", level=1)
    add_req_list(func_reqs, "No verified functional requirements.")

    # 3. Non-functional requirements
    doc.add_heading("3. Non-functional requirements", level=1)
    add_req_list(nfunc_reqs, "No verified non-functional requirements.")

    # 4. Constraints
    doc.add_heading("4. Constraints", level=1)
    add_req_list(const_reqs, "No verified constraints.")

    # 5. Unverified items (not confirmed)
    doc.add_heading("5. Unverified items (not confirmed)", level=1)
    if unverified_reqs:
        for r in unverified_reqs:
            p = doc.add_paragraph(style="List Bullet")
            r_id = p.add_run(f"{r.id}: ")
            r_id.bold = True
            p.add_run(f"{r.text} (Reason: unverified source evidence)")
            for ev in r.evidence:
                p_ev = doc.add_paragraph(style="Normal")
                p_ev.paragraph_format.left_indent = Inches(0.5)
                r_ev = p_ev.add_run(f"Evidence claimed: {ev.file_name} ({ev.kind}) - {ev.verify_note}")
                r_ev.italic = True
                r_ev.font.size = Pt(9.5)
    else:
        doc.add_paragraph("None. All extracted requirements passed evidence verification.")

    # 6. Conflicts
    doc.add_heading("6. Conflicts", level=1)
    if result.conflicts:
        for c in result.conflicts:
            status = "Resolved" if c.resolved else "Unresolved"
            p = doc.add_paragraph(style="List Bullet")
            r_st = p.add_run(f"[{status}] [{c.severity.upper()}] ({', '.join(c.requirement_ids)}): ")
            r_st.bold = True
            p.add_run(c.description)
    else:
        doc.add_paragraph("No conflicts detected.")

    # 7. Open questions
    doc.add_heading("7. Open questions", level=1)
    if result.gaps:
        for g in result.gaps:
            p = doc.add_paragraph(style="List Bullet")
            r_cat = p.add_run(f"{g.category.title()}: ")
            r_cat.bold = True
            p.add_run(g.question)
            if g.answer:
                p_ans = doc.add_paragraph(style="Normal")
                p_ans.paragraph_format.left_indent = Inches(0.5)
                r_ans = p_ans.add_run(f"Answer: {g.answer}")
                r_ans.italic = True
                r_ans.font.bold = True
    else:
        doc.add_paragraph("No open requirement gaps detected.")

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()
